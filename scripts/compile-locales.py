#!/usr/bin/env python3
"""Validate shared catalogs and generate native strings and offline beginner guides."""
import hashlib, html, json, re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
CAT=ROOT/'i18n'
OVER=ROOT/'android/overlay'
EN=json.loads((CAT/'en.json').read_text())
LANGS=json.loads((CAT/'languages.json').read_text())['locales']
def resource(key):return 'rs_'+re.sub('[^a-z0-9_]','_',key.lower())
def xml(value):return '"'+html.escape(value,quote=False).replace('\\','\\\\').replace("'","\\'").replace('"','\\"').replace('\n','\\n')+'"'
def placeholders(s):return sorted(re.findall(r'\{[a-z_]+\}|%\d+\$[ds]',s))
errors=[];catalogs={}
for lang in LANGS:
 tag=lang['tag']; p=CAT/(tag+'.json')
 if not p.exists():errors.append('Missing catalog: '+tag);continue
 data=json.loads(p.read_text());catalogs[tag]=data
 if set(data)!=set(EN):errors.append(tag+': missing/extra keys '+str(sorted(set(data)^set(EN))))
 for k,v in data.items():
  if not isinstance(v,str) or not v.strip():errors.append(tag+': empty '+k);continue
  if k in EN and placeholders(v)!=placeholders(EN[k]):errors.append(tag+': placeholders '+k)
  if k in EN:
   for side in ('^\\s+','\\s+$'):
    if re.findall(side,v)!=re.findall(side,EN[k]):errors.append(tag+': whitespace '+k)
   for protected in ('DELETE VPN','DELETE PAIR'):
    if EN[k].count(protected)!=v.count(protected):errors.append(tag+': confirmation phrase '+k)
if errors:raise SystemExit('\n'.join(errors))
# New presentation literals must enter the shared catalog before a build.
activity=(OVER/'java/org/strongswan/android/ui/RookstrideActivity.java')
if activity.exists():
 for literal in re.findall(r'\bt\(("(?:[^"\\]|\\.)*")\)',activity.read_text()):
  value=json.loads(literal)
  if value not in EN.values():errors.append('Uncatalogued app text: '+value)
if activity.exists():
 for key in re.findall(r'\btr\("([^"]+)"\)',activity.read_text()):
  if key not in EN:errors.append('Unknown app message key: '+key)
if errors:raise SystemExit('\n'.join(errors))
review=CAT/'reviews.json'
if not review.is_file():raise SystemExit('Missing translation review record; complete catalog review before building.')
if review.exists():
 records=json.loads(review.read_text())
 for tag in catalogs:
  if tag=='en':continue
  if records.get(tag,{}).get('translation_hash')!=hashlib.sha256((CAT/(tag+'.json')).read_bytes()).hexdigest():errors.append(tag+': unreviewed catalog edit')
  if records.get(tag,{}).get('plural_source_hash')!=hashlib.sha256((CAT/'plurals-en.json').read_bytes()).hexdigest():errors.append(tag+': stale English plural review')
  if records.get(tag,{}).get('plural_hash')!=hashlib.sha256((CAT/('plurals-'+tag+'.json')).read_bytes()).hexdigest():errors.append(tag+': unreviewed plural edit')
  for key,value in EN.items():
   if records.get(tag,{}).get('source_hashes',{}).get(key)!=hashlib.sha256(value.encode()).hexdigest():errors.append(tag+': stale review '+key)
 if errors:raise SystemExit('\n'.join(errors))
# Native resources; JSON catalogs stay the source of truth.
qualifiers={'en':'values','ru':'values-ru','fa':'values-fa','ar':'values-ar','zh-Hans':'values-b+zh+Hans'}
for lang in LANGS:
 tag=lang['tag'];data=catalogs[tag];dest=OVER/'res'/qualifiers[tag];dest.mkdir(parents=True,exist_ok=True)
 strings=['<?xml version="1.0" encoding="utf-8"?>','<!-- Generated by scripts/compile-locales.py. Edit i18n catalogs. -->','<resources>']
 strings += [f'    <string name="{resource(k)}" formatted="false">{xml(v)}</string>' for k,v in data.items()]
 plural=CAT/('plurals-'+tag+'.json')
 forms=json.loads(plural.read_text())['checkpoints_remaining'] if plural.exists() else {'one':'%1$d checkpoint remaining','other':'%1$d checkpoints remaining'}
 if 'other' not in forms or any(placeholders(v)!=['%1$d'] for v in forms.values()):raise SystemExit('Invalid plural '+tag)
 strings+=['    <plurals name="rs_checkpoints_remaining">']+[f'        <item quantity="{q}">{xml(v)}</item>' for q,v in forms.items()]+['    </plurals>','</resources>']
 (dest/'rookstride_strings.xml').write_text('\n'.join(strings)+'\n')
 # A small, translated first journey; the complete detailed English document remains available.
 e=lambda k:html.escape(data[k])
 body=f'<h1>{e("app.guide_title")}</h1><p>{e("start.intro")}</p><h2>{e("start.need_title")}</h2><ul>'+''.join('<li>'+e('start.need'+str(n))+'</li>' for n in range(1,5))+'</ul>'
 for key in ['download','add','pin','install','wait','resume','connect','check','invite']:
  body+=f'<h2>{e("start."+key)}</h2><p>{e("start."+key+"_copy")}</p>'
 body+=f'<h2>{e("start.reset_title")}</h2><p>{e("start.reset_copy")}</p><p>{e("start.reset_phrase")}</p><h2>{e("architecture.limits")}</h2><p>{e("architecture.limits_copy")}</p><p>{e("language.stories_english")}</p><p><a href="rookstride:full-guide">{e("app.advanced_guide")}</a> · <a href="rookstride:licenses">Licenses (English)</a> · <a href="rookstride:stories">{e("nav.worlds")}</a></p>'
 guide=f'<!doctype html><html lang="{tag}" dir="{lang["dir"]}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>body{{font:17px/1.65 sans-serif;padding:20px;margin:auto;max-width:720px;overflow-wrap:anywhere}}h1{{font-size:28px}}h2{{font-size:21px;margin-block-start:28px}}a{{color:#bb1727}}li{{margin-block:8px}}</style></head><body>{body}</body></html>'
 (OVER/'assets'/('guide-'+tag+'.html')).write_text(guide)
java=['package org.strongswan.android.rookstride;','import org.strongswan.android.R;','import java.util.*;','/** Generated shared-catalog index. */','final class RookStrings {','static final Map<String,Integer> KEYS=new HashMap<>(), SOURCE=new HashMap<>();','static {']
for k,v in EN.items():
 java.append('KEYS.put('+json.dumps(k)+',R.string.'+resource(k)+');')
 if k.startswith('m_'):java.append('SOURCE.put('+json.dumps(v,ensure_ascii=False)+',R.string.'+resource(k)+');')
java+=['}','}']
(OVER/'java/org/strongswan/android/rookstride/RookStrings.java').write_text('\n'.join(java)+'\n')
config=OVER/'res/xml/rookstride_locales.xml'
config.write_text('<?xml version="1.0" encoding="utf-8"?>\n<locale-config xmlns:android="http://schemas.android.com/apk/res/android">'+''.join(f'<locale android:name="{l["tag"]}"/>' for l in LANGS)+'</locale-config>\n')
print(f'Validated {len(EN)} shared messages × {len(catalogs)} languages; generated strings and offline guides.')
